// Builds src/lib/airports-large.ts from the OurAirports airports.csv (Unlicense / public domain).
// Usage: node scripts/build-airports.mjs <path-to-airports.csv> <output.ts>
// Keeps large and medium airports that have both an IATA and an ICAO code.
import { readFileSync, writeFileSync } from "node:fs";

const [inPath, outPath] = process.argv.slice(2);
if (!inPath || !outPath) {
  console.error("usage: node scripts/build-airports.mjs <airports.csv> <output.ts>");
  process.exit(1);
}

const text = readFileSync(inPath, "utf8");
if (text.length < 1_000_000) {
  console.error(`refusing a suspiciously small input (${text.length} bytes)`);
  process.exit(1);
}

/** Minimal CSV parser: quoted fields, doubled quotes, commas and newlines inside quotes. */
function parseCsv(src) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (quoted) {
      if (c === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && src[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const [header, ...data] = parseCsv(text);
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`column missing: ${name}`);
  return i;
};
const C = {
  type: col("type"),
  name: col("name"),
  lat: col("latitude_deg"),
  lon: col("longitude_deg"),
  city: col("municipality"),
  icao: col("icao_code"),
  iata: col("iata_code"),
};

const seen = new Set();
const out = [];
for (const r of data) {
  if (r[C.type] !== "large_airport" && r[C.type] !== "medium_airport") continue;
  const iata = (r[C.iata] ?? "").trim().toUpperCase();
  const icao = (r[C.icao] ?? "").trim().toUpperCase();
  if (!/^[A-Z0-9]{3}$/.test(iata) || !/^[A-Z0-9]{4}$/.test(icao)) continue;
  const lat = Number(r[C.lat]);
  const lon = Number(r[C.lon]);
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  if (seen.has(icao) || seen.has(iata)) continue;
  seen.add(icao);
  seen.add(iata);
  out.push([
    iata,
    icao,
    r[C.name].trim(),
    (r[C.city] ?? "").trim(),
    Math.round(lat * 10000) / 10000,
    Math.round(lon * 10000) / 10000,
  ]);
}
out.sort((a, b) => a[0].localeCompare(b[0]));

const file = `// GENERATED by scripts/build-airports.mjs from OurAirports airports.csv (Unlicense / public domain,
// https://ourairports.com/data/). Large and medium airports with IATA and ICAO codes.
// Do not edit by hand. Rows: [iata, icao, name, city, lat, lon].
export type AirportRow = [string, string, string, string, number, number];

export const LARGE_AIRPORT_ROWS: AirportRow[] = ${JSON.stringify(out)};
`;
writeFileSync(outPath, file);
console.log(`wrote ${out.length} airports to ${outPath}`);
